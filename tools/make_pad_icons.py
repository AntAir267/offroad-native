#!/usr/bin/env python3
"""Draws the Xbox button icons (Pillow, DejaVu Sans Bold) into runtime/pad_icons.h: 54 x 54 RGBA cells, zlib
compressed. runtime/padgame.c adds them to the game's fonts. Usage: tools/make_pad_icons.py [--preview FILE.png]"""
import sys, zlib
from PIL import Image, ImageDraw, ImageFont

CELL, S = 54, 8
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
WHITE, DARK, EDGE = (255, 255, 255, 255), (38, 38, 42, 255), (205, 205, 210, 255)
GREEN, RED, BLUE, YELLOW = (92, 190, 52, 255), (222, 60, 48, 255), (46, 118, 226, 255), (244, 190, 30, 255)


def text(d, s, size, fill=WHITE, dy=0):
    f = ImageFont.truetype(FONT, size * S)
    n = CELL * S
    d.text((n // 2, n // 2 + dy * S), s, font=f, fill=fill, anchor="mm")


def face(colour=None):
    im = Image.new("RGBA", (CELL * S, CELL * S), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    if colour:
        d.ellipse((2 * S, 2 * S, (CELL - 2) * S, (CELL - 2) * S), fill=colour, outline=DARK, width=2 * S)
    return im, d


def letter(ch, colour):
    im, d = face(colour)
    text(d, ch, 31, WHITE if colour != YELLOW else DARK)
    return im


def bumper(s):
    im, d = face()
    d.rounded_rectangle((1 * S, 11 * S, 53 * S, 43 * S), radius=10 * S, fill=DARK, outline=EDGE, width=2 * S)
    text(d, s, 22)
    return im


def trigger(s):
    im, d = face()
    d.polygon([(7 * S, 52 * S), (47 * S, 52 * S), (47 * S, 18 * S), (36 * S, 3 * S), (18 * S, 3 * S), (7 * S, 18 * S)],
              fill=DARK, outline=EDGE)
    text(d, s, 21, dy=3)
    return im


def small(draw):
    im, d = face(DARK)
    draw(d)
    return im


def back(d):
    a, b = 16 * S, 24 * S
    d.rounded_rectangle((a, 18 * S, a + b, 34 * S), radius=2 * S, outline=WHITE, width=3 * S)
    d.rounded_rectangle((a + 5 * S, 22 * S, a + b + 5 * S, 38 * S), radius=2 * S, fill=DARK, outline=WHITE, width=3 * S)


def start(d):
    for y in (18, 26, 34):
        d.rectangle((15 * S, y * S, 39 * S, (y + 3) * S), fill=WHITE)


def stick(s):
    def draw(d):
        d.ellipse((10 * S, 10 * S, 44 * S, 44 * S), outline=EDGE, width=3 * S)
    im = small(draw)
    text(ImageDraw.Draw(im), s, 22)
    return im


def guide(d):
    text(d, "X", 28)


ICONS = [letter("A", GREEN), letter("B", RED), letter("X", BLUE), letter("Y", YELLOW), bumper("LB"), bumper("RB"),
         trigger("LT"), trigger("RT"), small(back), small(start), stick("L"), stick("R"), small(guide)]
cells = [i.resize((CELL, CELL), Image.LANCZOS) for i in ICONS]
raw = b"".join(c.tobytes() for c in cells)
z = zlib.compress(raw, 9)
with open("runtime/pad_icons.h", "w", newline="\n") as f:
    f.write("/* Generated by tools/make_pad_icons.py: %d cells of %d x %d RGBA, zlib compressed. */\n" % (len(cells), CELL, CELL))
    f.write("#define PAD_ICON_COUNT %d\n#define PAD_ICON_CELL %d\nstatic const unsigned char pad_icons_z[] = {\n" % (len(cells), CELL))
    for i in range(0, len(z), 20):
        f.write("    " + ",".join(str(b) for b in z[i:i + 20]) + ",\n")
    f.write("};\n")
if "--preview" in sys.argv:
    p = Image.new("RGBA", (len(cells) * (CELL * 2 + 8), CELL * 2 + 8), (150, 110, 70, 255))
    for i, c in enumerate(cells):
        b = c.resize((CELL * 2, CELL * 2), Image.NEAREST)
        p.paste(b, (i * (CELL * 2 + 8) + 4, 4), b)
    p.save(sys.argv[sys.argv.index("--preview") + 1])
print(len(cells), "cells,", len(z), "bytes")
